import assert from "node:assert/strict";
import { test } from "node:test";
import { randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";
import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import * as schema from "../src/db/schema.ts";
import type { CurrentUser } from "../src/services/auth.ts";
test("private intake credentials isolate firm/session, expire, rotate and revoke without storing raw tokens", async () => {
  process.env.DATABASE_URL ??= "postgres://localhost/unused_intake_access_test";
  const { createIntakeAccessService, issueIntakeToken, resumePath } = await import("../src/services/intake-access.ts");
  const pg = await PGlite.create();
  try {
    const journal = JSON.parse(await readFile(new URL("../drizzle/meta/_journal.json", import.meta.url), "utf8"));
    for (const entry of journal.entries as { tag: string }[]) await pg.exec(await readFile(new URL(`../drizzle/${entry.tag}.sql`, import.meta.url), "utf8"));
    const firm = randomUUID(), foreignFirm = randomUUID(), userId = randomUUID(), conversationId = randomUUID(), intakeId = randomUUID();
    await pg.query("INSERT INTO law_firms (id,name,slug) VALUES ($1,'Session Firm','session-firm'),($2,'Other Firm','other-firm')", [firm, foreignFirm]);
    await pg.query("INSERT INTO users (id,email,law_firm_id) VALUES ($1,'session@test.example',$2)", [userId, firm]);
    await pg.query("INSERT INTO voice_conversations (id,consented_at) VALUES ($1,now())", [conversationId]);
    await pg.query("INSERT INTO intake_sessions (id,law_firm_id,voice_conversation_id,config,client_name) VALUES ($1,$2,$3,$4,'Session Client')", [intakeId, firm, conversationId, JSON.stringify({ sections: [{ id: "contact", title: "Contact", questions: [{ id: "name", text: "Your name?" }] }] })]);
    await pg.query("INSERT INTO voice_messages (conversation_id,role,text) VALUES ($1,'scribe','Your name?'),($1,'client','Session Client')", [conversationId]);
    await pg.query("INSERT INTO intake_responses (session_id,question_id,question_text,value) VALUES ($1,'name','Your name?','Session Client')", [intakeId]);
    const database = drizzle(pg, { schema }) as unknown as Parameters<typeof createIntakeAccessService>[0];
    const service = createIntakeAccessService(database);
    const access = await issueIntakeToken(database!, firm, intakeId);
    const actor = { id: userId, role: "attorney", firm: { id: firm } } as CurrentUser;
    const stored = (await pg.query<{ token_hash: string }>("SELECT token_hash FROM intake_access WHERE session_id=$1", [intakeId])).rows[0];
    assert.notEqual(stored.token_hash, access.token); assert.equal(stored.token_hash.length, 64);
    assert.match(resumePath("session-firm", access.token), /^\/intake\/session-firm\/resume#[A-Za-z0-9_-]{43}$/);
    const resumed = await service.resume("session-firm", access.token);
    assert.equal(resumed.session.id, intakeId); assert.equal(resumed.messages.length, 2); assert.deepEqual(resumed.answeredIds, ["name"]);
    await assert.rejects(service.authorize("other-firm", access.token), /invalid/);
    await assert.rejects(service.authorize("session-firm", access.token, randomUUID()), /invalid/);
    await assert.rejects(service.authorize("session-firm", "missing"), /invalid/);
    await assert.rejects(service.manage({ ...actor, role: "staff" }, intakeId, "rotate"), /administrator/);
    await assert.rejects(service.manage({ ...actor, firm: { id: foreignFirm } } as CurrentUser, intakeId, "rotate"), /unavailable/);
    const replacement = await service.manage(actor, intakeId, "rotate"); assert.ok(replacement);
    await assert.rejects(service.resume("session-firm", access.token), /invalid/);
    await service.authorize("session-firm", replacement.token, conversationId);
    await service.manage(actor, intakeId, "revoke");
    await assert.rejects(service.resume("session-firm", replacement.token), /invalid/);
    const expiring = await service.manage(actor, intakeId, "rotate"); assert.ok(expiring);
    await pg.query("UPDATE intake_access SET expires_at=now()-interval '1 minute' WHERE session_id=$1", [intakeId]);
    await assert.rejects(service.resume("session-firm", expiring.token), /invalid/);
    const closing = await service.manage(actor, intakeId, "rotate"); assert.ok(closing);
    await pg.query("UPDATE voice_conversations SET completed_at=now() WHERE id=$1", [conversationId]);
    await assert.rejects(service.resume("session-firm", closing.token), /closed/);
  } finally { await pg.close(); }
});
